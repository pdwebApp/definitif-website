def get_published_insights(section):
    return [
        article
        for article in INSIGHTS.get(section, [])
        if article.get("status") == "published"
    ]


def get_featured_insight():
    for section in INSIGHTS:
        for article in get_published_insights(section):
            if article.get("featured"):
                return section, article

    return None, None


def get_insight(section, slug):
    for article in get_published_insights(section):
        if article["slug"] == slug:
            return article

    return None


def get_related_insights(section, current_slug, limit=3):
    related = [
        article
        for article in get_published_insights(section)
        if article["slug"] != current_slug
    ]

    if len(related) >= limit:
        return related[:limit]

    for other_section in INSIGHTS:
        if other_section == section:
            continue

        for article in get_published_insights(other_section):
            if article["slug"] == current_slug:
                continue

            related.append(article)

            if len(related) >= limit:
                return related

    return related[:limit]